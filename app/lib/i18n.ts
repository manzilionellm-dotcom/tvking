const DICT: Record<string, Dict> = { en, fr, es, pt, de, it, ar, zh, ru, tr };
const RTL = new Set(["ar"]);
const DEFAULT_LOCALE = "en";

/** Choisit la locale supportée la plus proche de la langue de l'appareil. */
function detectLocale(): string {
  if (typeof navigator === "undefined") return DEFAULT_LOCALE;
  const prefs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language];
  for (const p of prefs) {
    if (!p) continue;
    const base = p.toLowerCase().split("-")[0];
    if (base in DICT) return base;
  }
  return DEFAULT_LOCALE;
}

// Locale figée au chargement côté client (la langue de la TV ne change pas en
// cours d'usage). En SSR/export statique on rend DEFAULT_LOCALE puis le client
// re-rend dans la bonne langue (useSyncExternalStore gère ce basculement).
let clientLocale: string | null = null;
function getClientLocale(): string {
  if (clientLocale === null) clientLocale = detectLocale();
  return clientLocale;
}

export function currentLocale(): string {
  return typeof window === "undefined" ? DEFAULT_LOCALE : getClientLocale();
}

export function isRtl(): boolean {
  return RTL.has(currentLocale());
}

/** Applique <html lang> + dir selon la langue détectée (appelé au montage). */
export function applyLocale(): void {
  if (typeof document === "undefined") return;
  const loc = getClientLocale();
  document.documentElement.lang = loc;
  document.documentElement.dir = RTL.has(loc) ? "rtl" : "ltr";
}

/** Traduit une clé, avec interpolation de {tokens}. Repli : locale → en → clé. */
export function translate(locale: string, key: string, vars?: Record<string, string | number>): string {
  const table = DICT[locale] ?? DICT[DEFAULT_LOCALE];
  let s = table[key] ?? DICT[DEFAULT_LOCALE][key] ?? key;
  if (vars) {
    for (const k in vars) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
  }
  return s;
}

// --- Hook réactif : bascule de DEFAULT_LOCALE (SSR) vers la langue détectée ---
const NO_OP = () => () => {};
export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const locale = useSyncExternalStore(
    NO_OP,
    () => getClientLocale(),
    () => DEFAULT_LOCALE,
  );
  return (key, vars) => translate(locale, key, vars);
}
